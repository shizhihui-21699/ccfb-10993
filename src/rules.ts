/**
 * 规则目录。
 *
 * 权重设计(0-100,最终按组合与置信度折算成总分):
 *
 *  - 安装脚本里直接跑命令 / 拉远端脚本:权重最高的单项。npm 投毒几乎都从这个入口起爆,
 *    且在 `npm install` 时 100% 会执行,没有运行时条件可言。
 *  - 收凭据(env / SSH / ~/.npmrc / 浏览器 cookie)再外发:单项未必致命,但"读 + 发"组合
 *    在 scorer 里会拿到乘数,因为它是最典型的窃密链。
 *  - 动态执行(eval / new Function / vm)本身在正经库里不算罕见(模板引擎、序列化),
 *    所以基础权重压得低,只有和"不可信输入"或"网络响应"同时出现才升级。
 *  - base64/hex 混淆只是信号,单独出现给低权重;若解出第二层并命中高危规则,
 *    由解码器把第二层的 finding 提上来(见 deobfuscate.ts)。
 *  - 反分析(检测 sandbox / 调试器、读取 /proc、篡改 npm 配置)属于明确的对抗意图,
 *    权重给到 high 档,它没有正当用途。
 */

