export const RULE_BY_ID = new Map(RULES.map((r) => [r.id, r]));

export function rule(id: string): RuleDefinition {
  const found = RULE_BY_ID.get(id);
  if (!found) throw new Error(`未知规则 id: ${id}`);
  return found;
}
